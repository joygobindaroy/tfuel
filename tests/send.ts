import { makeDb } from "./fakedb";
(globalThis as any).__fakeDb = makeDb();
process.env.SERVER_SECRET = "x".repeat(32);
process.env.BOT_TOKEN = "123:abc";
import assert from "node:assert/strict";
const mails: any[] = [];
(globalThis as any).__fakeMail = async (to: string, s: string, b: any) => { mails.push({ to, s, text: b.text }); };
(globalThis as any).fetch = async () => ({ json: async () => ({ ok: true, result: {} }) });
(async () => {
  const { db } = await import("../lib/firebase");
  const { sendCoins } = await import("../lib/transfer");
  const { getSettings, invalidateSettings } = await import("../lib/settings");
  const old = Date.now() - 3 * 86400000;
  await db().ref("users/1").set({ name: "Alice", balance: 100000, created_at: old });
  await db().ref("users/2").set({ name: "Bob", balance: 0, created_at: old });
  await db().ref("users/3").set({ name: "New", balance: 100000, created_at: Date.now() });
  await db().ref("user_prefs/1/email").set({ addr: "a@x.co", verified: true });
  await db().ref("user_prefs/2/email").set({ addr: "b@x.co", verified: true });
  await db().ref("settings").set({ send_enabled: true, send_fee_pct: 1, send_min: 1000, send_daily_limit: 50000, send_min_age_hours: 24, email_money: true });
  invalidateSettings();
  const s = await getSettings(true);
  const r = await sendCoins({ id: "1", name: "Alice" }, "2", 10000, s, "hi");
  assert.equal(r.fee, 100);
  assert.equal((await db().ref("users/1/balance").get()).val(), 100000 - 10100);
  assert.equal((await db().ref("users/2/balance").get()).val(), 10000);
  assert.deepEqual(mails.map((m) => m.to).sort(), ["a@x.co", "b@x.co"], "both parties get an email");
  assert.ok(mails.find((m) => m.to === "b@x.co").text.includes("10,000 TFUEL") || mails.find((m) => m.to === "b@x.co").text.includes("TFUEL"));
  await assert.rejects(sendCoins({ id: "1", name: "Alice" }, "1", 5000, s), /send_self/);
  await assert.rejects(sendCoins({ id: "1", name: "Alice" }, "2", 500, s), /send_min/);
  await assert.rejects(sendCoins({ id: "3", name: "New" }, "2", 5000, s), /send_too_new/);
  await assert.rejects(sendCoins({ id: "1", name: "Alice" }, "2", 45000, s), /send_limit/, "daily cap incl. fee");
  assert.equal((await db().ref("users/1/balance").get()).val(), 100000 - 10100, "failed send changes nothing");
  await assert.rejects(sendCoins({ id: "2", name: "Bob" }, "1", 20000, s), /insufficient/);
  // user switched emails off
  await db().ref("user_prefs/2/mail_money").set(false);
  mails.length = 0;
  await sendCoins({ id: "1", name: "Alice" }, "2", 1000, s);
  assert.deepEqual(mails.map((m) => m.to), ["a@x.co"]);
  console.log("send OK");
})().catch((e) => { console.error("FAIL", e); process.exit(1); });
