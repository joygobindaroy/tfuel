import { makeDb } from "./fakedb";
(globalThis as any).__fakeDb = makeDb();
process.env.SERVER_SECRET = "x".repeat(32);
process.env.BOT_TOKEN = "123:abc";
process.env.NEXT_PUBLIC_BOT_LINK = "https://t.me/mybot/app";
import assert from "node:assert/strict";
(globalThis as any).fetch = async () => ({ json: async () => ({ ok: true, result: {} }) });
(async () => {
  const { db } = await import("../lib/firebase");
  const M = await import("../lib/v24");
  const { sendCoins } = await import("../lib/transfer");
  const { getSettings, invalidateSettings } = await import("../lib/settings");
  const { getRefCode } = await import("../lib/refcode");
  const old = Date.now() - 3 * 86400000;
  await db().ref("users/1").set({ name: "Alice", balance: 100000, created_at: old });
  await db().ref("users/2").set({ name: "Bobshop", balance: 0, created_at: old });
  await db().ref("settings").set({ send_enabled: true, send_fee_pct: 1, send_min: 1000, send_daily_limit: 500000, send_min_age_hours: 24 });
  invalidateSettings();
  const s = await getSettings(true);
  await assert.rejects(M.merchantSet("2", { name: "x" }));
  const m = await M.merchantSet("2", { name: "Bob <b>Cafe", amt: "5.5", asset: "usdt", on: true });
  assert.equal(m.asset, "usdt"); assert.equal(m.amt, 5.5); assert.ok(!m.name.includes("<"));
  const code = await getRefCode("2");
  const pub = await M.merchantPub(code);
  assert.equal(pub.amt, 5.5);
  assert.match(await M.merchantLink("2"), /^https:\/\/t\.me\/mybot\/app\?startapp=mer_[A-Za-z0-9]{10}$/);
  await M.merchantSet("2", { name: "Bob Cafe", amt: 0, asset: "tfuel", on: true });
  await sendCoins({ id: "1", name: "Alice" }, "2", 10000, s, "coffee");
  await sendCoins({ id: "1", name: "Alice" }, "2", 2000, s, "");
  await new Promise((r) => setTimeout(r, 150));
  const sales = await M.merchantSales("2");
  assert.equal(sales.today.n, 2); assert.equal(sales.today.tfuel, 12000); assert.equal(sales.all.n, 2); assert.equal(sales.list.length, 2);
  assert.ok(!JSON.stringify(sales.list).includes("Alice"), "customer name is masked");
  // closed shop: no sale recorded, public info hidden
  await M.merchantSet("2", { name: "Bob Cafe", on: false });
  await sendCoins({ id: "1", name: "Alice" }, "2", 1000, s);
  await new Promise((r) => setTimeout(r, 150));
  assert.equal((await M.merchantSales("2")).all.n, 2);
  await assert.rejects(M.merchantPub(code), /isn't accepting/);
  await assert.rejects(M.merchantPub("bad"));
  console.log("v24 OK");
})().catch((e) => { console.error("FAIL", e); process.exit(1); });
